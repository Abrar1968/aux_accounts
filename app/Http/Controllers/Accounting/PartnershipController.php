<?php

namespace App\Http\Controllers\Accounting;

use App\Http\Controllers\Controller;
use App\Http\Requests\Accounting\StoreAssignmentRequest;
use App\Http\Requests\Accounting\StoreCollaboratorRequest;
use App\Http\Requests\Accounting\StorePartnershipEarningRequest;
use App\Models\PartnershipRevenue;
use App\Services\Accounting\PartnershipService;
use App\Services\Shared\ListingService;
use Illuminate\Http\Request;
use Inertia\Inertia;
use Inertia\Response;

class PartnershipController extends Controller
{
    public function __construct(private readonly PartnershipService $partnerships)
    {
    }

    public function index(Request $request, ListingService $list): Response
    {
        return Inertia::render('Accounting/Partnerships/Index', $this->partnerships->overview()
            + ['revenues' => $list->page('partnership_revenues', $request->query())]);
    }

    public function storeCollaborator(StoreCollaboratorRequest $request)
    {
        $c = $this->partnerships->createCollaborator($request->validated());

        return $this->toast("Collaborator {$c->code} saved.");
    }

    public function storeAssignment(StoreAssignmentRequest $request)
    {
        $a = $this->partnerships->createAssignment($request->validated());

        return $this->toast("Assignment {$a->code} saved. Monthly rows are generated by the daily automation.");
    }

    public function setEarning(StorePartnershipEarningRequest $request, PartnershipRevenue $revenue)
    {
        $r = $this->partnerships->setEarning($revenue, $request->validated('gross_sales'), $request->validated('direct_amount'), $request->validated('notes'));

        return $this->toast("{$r->code}: recognised ৳".number_format((float) $r->recognized_revenue, 2).'.');
    }
}
